"""Aerodynamic drag (CdA) fitted from race files, and bike-split projection.

The rules this module enforces, each a way an earlier hand-rolled version was
biased:
- fit and projection share ONE set of physics constants (Crr, rho, drivetrain
  loss, mass) -- an effective CdA in one meter's watts is only meaningful then;
- station wind is measured at 10 m, so it is scaled down to rider height;
- the headwind a rider feels depends on the course bearing, so it is resolved
  per segment as v_wind * cos(wind_from - heading) rather than assuming half the
  distance straight into it;
- wind does not cancel on an out-and-back.
"""

from __future__ import annotations

import math

import numpy as np
import pandas as pd
import pytest

from trinity.analysis.aero import (
    Chunk,
    Physics,
    fit_cda,
    fit_cda_from_time,
    head_wind,
    simulate,
)

PHYS = Physics()


def out_and_back(km=90, heading=0.0, grade=0.0):
    half = [Chunk(1000.0, grade, heading) for _ in range(km // 2)]
    back = [Chunk(1000.0, -grade, (heading + 180) % 360) for _ in range(km // 2)]
    return half + back


def synth_stream(chunks, power, cda, wind_ms, wind_from, phys=PHYS, lat0=52.0, lng0=16.0):
    """1 Hz stream of a rider holding `power` over `chunks` -- generated by the SAME
    physics the fit uses, so a correct fit must recover `cda`."""
    from trinity.analysis.aero import speed_at_power

    t, dist, alt, lat, lng, watts = [], [], [], [], [], []
    clock = d = a = 0.0
    la, lo = lat0, lng0
    for c in chunks:
        hw = head_wind(wind_ms, wind_from, c.heading_deg, phys)
        v = speed_at_power(power, cda, c.grade, hw, phys)
        steps = int(round(c.length_m / v))
        for _ in range(steps):
            clock += 1
            step = c.length_m / steps
            d += step
            a += step * c.grade
            la += step * math.cos(math.radians(c.heading_deg)) / 111_320
            lo += step * math.sin(math.radians(c.heading_deg)) / (111_320 * math.cos(math.radians(la)))
            t.append(clock)
            dist.append(d)
            alt.append(a)
            lat.append(la)
            lng.append(lo)
            watts.append(power)
    return pd.DataFrame({"t": t, "dist": dist, "alt": alt, "lat": lat, "lng": lng, "watts": watts})


def test_wind_does_not_cancel_on_an_out_and_back():
    course = out_and_back()
    calm = simulate(course, 200, 0.18, 0.0, 0.0, PHYS)
    windy = simulate(course, 200, 0.18, 6.0, 0.0, PHYS)
    assert windy > calm, "time lost into the wind exceeds time gained with it"


def test_station_wind_is_scaled_to_rider_height():
    full = Physics(wind_height_factor=1.0)
    assert head_wind(10.0, 0.0, 0.0, PHYS) == pytest.approx(10.0 * PHYS.wind_height_factor)
    assert head_wind(10.0, 0.0, 0.0, full) == pytest.approx(10.0)
    assert 0.55 <= PHYS.wind_height_factor <= 0.70


def test_headwind_follows_the_course_bearing():
    assert head_wind(5.0, 270.0, 270.0, PHYS) > 0, "riding west into a westerly"
    assert head_wind(5.0, 270.0, 90.0, PHYS) < 0, "riding east with a westerly behind"
    assert abs(head_wind(5.0, 270.0, 0.0, PHYS)) < 1e-9, "pure crosswind has no head component"


def test_crosswind_course_is_not_slowed_by_the_head_component():
    course = out_and_back(heading=0.0)          # north-south
    calm = simulate(course, 200, 0.18, 0.0, 90.0, PHYS)
    cross = simulate(course, 200, 0.18, 6.0, 90.0, PHYS)   # wind from the east
    assert cross == pytest.approx(calm, rel=1e-6)


def test_fit_recovers_known_cda_from_a_windy_file():
    course = [Chunk(250.0, 0.0, h) for h in np.tile(np.arange(0, 360, 30), 30)]
    df = synth_stream(course, 205.0, 0.172, 5.0, 225.0)
    r = fit_cda(df, wind_ms=5.0, wind_from_deg=225.0, phys=PHYS)
    assert r.cda == pytest.approx(0.172, abs=0.004)
    assert r.used_s > 0.5 * df["t"].max()


def test_ignoring_wind_height_biases_the_fit_low():
    """A fit that applies full 10 m wind at rider height attributes too much power
    to wind and too little to drag -- the direction the review warned about."""
    course = [Chunk(250.0, 0.0, h) for h in np.tile(np.arange(0, 360, 30), 30)]
    df = synth_stream(course, 205.0, 0.175, 6.0, 0.0)
    honest = fit_cda(df, wind_ms=6.0, wind_from_deg=0.0, phys=PHYS).cda
    naive = fit_cda(df, wind_ms=6.0, wind_from_deg=0.0,
                    phys=Physics(wind_height_factor=1.0)).cda
    assert naive < honest


def test_time_based_fit_for_a_file_without_power():
    """Syców 2026 had a broken meter: fit CdA from time at an assumed power."""
    course = out_and_back(km=90, heading=45.0, grade=0.004)
    actual = simulate(course, 225.0, 0.180, 4.0, 225.0, PHYS)
    cda = fit_cda_from_time(course, 225.0, actual, 4.0, 225.0, PHYS)
    assert cda == pytest.approx(0.180, abs=0.001)


def test_reconstructed_course_keeps_the_full_distance():
    """Regression: chunking a stream dropped the gap between samples at every chunk
    boundary and any chunk spanning a GPS gap, so a 89.2 km course came back as
    85.2 km -- and every time-based fit then compared the full race time against a
    shorter course, inflating CdA."""
    from trinity.analysis.aero import chunks_from_stream

    course = [Chunk(250.0, 0.0, h) for h in np.tile(np.arange(0, 360, 30), 30)]
    df = synth_stream(course, 205.0, 0.18, 0.0, 0.0)
    df = df.drop(index=df.index[3000:3060])          # a GPS dropout mid-ride
    got = sum(c.length_m for c in chunks_from_stream(df, 1000.0))
    assert got == pytest.approx(df["dist"].max() - df["dist"].min(), rel=0.002)


def test_fit_and_projection_round_trip_with_shared_constants():
    course = out_and_back(km=60)
    df = synth_stream(course, 190.0, 0.185, 3.0, 45.0)
    cda = fit_cda(df, wind_ms=3.0, wind_from_deg=45.0, phys=PHYS).cda
    predicted = simulate(course, 190.0, cda, 3.0, 45.0, PHYS)
    assert predicted == pytest.approx(df["t"].max(), rel=0.01)
